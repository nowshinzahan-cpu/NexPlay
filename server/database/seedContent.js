function slugify(title) {
  return title
    .toLowerCase()
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '') // strip accents
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/(^-|-$)/g, '');
}

function posterFor(title) {
  const slug = slugify(title);
  return `https://picsum.photos/seed/${slug}-poster/500/750`;
}

function backdropFor(title) {
  const slug = slugify(title);
  return `https://picsum.photos/seed/${slug}-backdrop/1280/720`;
}

