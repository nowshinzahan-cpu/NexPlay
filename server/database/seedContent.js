const contentDataWithImages = contentData.map((item) => ({
  ...item,
  poster: posterFor(item.title),
  backdrop: backdropFor(item.title)
}));

async function seedContent() {
  try {
    await mongoose.connect(MONGO_URI);
    console.log(`Connected to MongoDB: ${MONGO_URI}\n`);

    await Content.deleteMany({});
    console.log('✓ Cleared existing content\n');

    const inserted = await Content.insertMany(contentDataWithImages);
    console.log(`✓ Seeded ${inserted.length} content items\n`);

    // Sanity check: confirm every inserted doc has a poster and backdrop.
    const missingImages = await Content.countDocuments({
      $or: [
        { poster: { $in: [null, ''] } },
        { backdrop: { $in: [null, ''] } }
      ]
    });
    if (missingImages > 0) {
      console.warn(`⚠ Warning: ${missingImages} item(s) are missing an image!`);
    } else {
      console.log('✓ Verified: every item has a poster and backdrop image\n');
    }

    const movieCount = await Content.countDocuments({ type: 'MOVIE' });
    const tvCount = await Content.countDocuments({ type: 'TV_SERIES' });
    const webCount = await Content.countDocuments({ type: 'WEB_SERIES' });
    const animeCount = await Content.countDocuments({ type: 'ANIME' });
    const docCount = await Content.countDocuments({ type: 'DOCUMENTARY' });
    const upcomingCount = await Content.countDocuments({ status: 'Upcoming' });

    console.log('  Content Breakdown:');
    console.log(`  ${' '.repeat(25)}`);
    console.log(`  Movies:        ${movieCount}`);
    console.log(`  TV Series:     ${tvCount}`);
    console.log(`  Web Series:    ${webCount}`);
    console.log(`  Anime:         ${animeCount}`);
    console.log(`  Documentaries: ${docCount}`);
    console.log(`  ─────────────────────`);
    console.log(`  Total:         ${inserted.length}`);
    console.log(`  Upcoming:      ${upcomingCount}`);
    console.log('');
    console.log('✓ Seed complete!');

    process.exit(0);
  } catch (error) {
    console.error(`Seed failed: ${error.message}`);
    process.exit(1);
  }
}

seedContent();